import { fireEvent, render, screen } from "@testing-library/react";
import { describe, expect, it } from "vitest";

import type { AssessmentResult, CropResponse } from "@bazarbeat/shared";
import "../../../lib/i18n.js";
import {
  ListingWizardProvider,
  type WizardError,
} from "../context/listing-wizard-context.js";
import { Step3AiResult } from "./step-3-ai-result.js";

const mockCrop: CropResponse = {
  id: "0123456789abcdef01234567",
  slug: "bitter-gourd",
  nameEn: "Bitter Gourd",
  nameBn: "করলা",
  unit: "KG",
  minLotKg: 10,
  maxLotKg: 1000,
  shelfLifeHours: 120,
  gradeGuide: { A: "Firm, rich green", B: "Minor blemishes", C: "Ripe and usable" },
  minIncrementPerKg: 100,
  imageUrl: "/images/crops/bitter-gourd.svg",
};

const createMockAssessment = (
  grade: "A" | "B" | "C",
  confidence = 0.92,
  degraded = false,
): AssessmentResult => ({
  grade,
  confidence,
  confidenceBand: confidence >= 0.85 ? "HIGH" : "MEDIUM",
  classProbabilities: { A: grade === "A" ? 0.8 : 0.1, B: grade === "B" ? 0.7 : 0.2, C: grade === "C" ? 0.7 : 0.1 },
  qualityNotes: [
    "Uniform deep green color and defined ridges",
    "Firm texture with no post-harvest cuts or soft spots",
  ],
  cropMatch: true,
  modelVersion: "mock-1.0",
  provider: "mock",
  degraded,
  assessedAt: new Date().toISOString(),
  assessmentToken: "sample-token-123",
});

function renderStep3(options: {
  assessment?: AssessmentResult | null;
  error?: WizardError | null;
  crop?: CropResponse | null;
}): ReturnType<typeof render> {
  return render(
    <ListingWizardProvider
      initialStep={3}
      initialCrop={options.crop ?? mockCrop}
      initialAssessment={options.assessment ?? null}
      initialError={options.error ?? null}
    >
      <Step3AiResult />
    </ListingWizardProvider>,
  );
}

describe("Step3AiResult component", () => {
  it("renders Grade A assessment with letter clearly visible, confidence band, and reasons", () => {
    const assessment = createMockAssessment("A", 0.95);
    renderStep3({ assessment });

    const badge = screen.getByTestId("grade-badge-a");
    expect(badge).toBeInTheDocument();
    expect(badge).toHaveTextContent("A");
    expect(badge).toHaveAttribute("aria-label", "Grade A");

    expect(screen.getByTestId("ai-confidence-band")).toHaveTextContent("High confidence (95%)");
    expect(screen.getByTestId("ai-reasons")).toHaveTextContent(
      "Uniform deep green color and defined ridges",
    );
    expect(screen.queryByTestId("degraded-notice")).not.toBeInTheDocument();
  });

  it("renders Grade B assessment with letter clearly visible and medium confidence", () => {
    const assessment = createMockAssessment("B", 0.75);
    renderStep3({ assessment });

    const badge = screen.getByTestId("grade-badge-b");
    expect(badge).toBeInTheDocument();
    expect(badge).toHaveTextContent("B");
    expect(badge).toHaveAttribute("aria-label", "Grade B");
    expect(screen.getByTestId("ai-confidence-band")).toHaveTextContent("Medium confidence (75%)");
  });

  it("renders Grade C assessment with letter clearly visible", () => {
    const assessment = createMockAssessment("C", 0.65);
    renderStep3({ assessment });

    const badge = screen.getByTestId("grade-badge-c");
    expect(badge).toBeInTheDocument();
    expect(badge).toHaveTextContent("C");
    expect(badge).toHaveAttribute("aria-label", "Grade C");
  });

  it("displays gentle offline notice when degraded is true", () => {
    const assessment = createMockAssessment("A", 0.88, true);
    renderStep3({ assessment });

    const notice = screen.getByTestId("degraded-notice");
    expect(notice).toBeInTheDocument();
    expect(notice).toHaveTextContent(/offline estimate mode/i);
  });

  it("displays AI-assessed tooltip with explanation on click or hover", () => {
    const assessment = createMockAssessment("A");
    renderStep3({ assessment });

    const badge = screen.getByTestId("ai-assessed-badge");
    expect(badge).toHaveTextContent("AI-assessed");

    // Tooltip is initially closed
    expect(screen.queryByTestId("ai-assessed-tooltip")).not.toBeInTheDocument();

    // Click/hover opens tooltip
    fireEvent.click(badge);
    expect(screen.getByTestId("ai-assessed-tooltip")).toHaveTextContent(
      /This grade is generated by our AI model based on visual quality features/i,
    );
  });

  it("renders CROP_MISMATCH error state with clear diagnosis and retake flow", () => {
    renderStep3({
      error: { code: "CROP_MISMATCH", message: "Crop does not match photos" },
    });

    const errorAlert = screen.getByTestId("ai-error-crop-mismatch");
    expect(errorAlert).toBeInTheDocument();
    expect(errorAlert).toHaveTextContent(/Crop mismatch detected/i);
    expect(errorAlert).toHaveTextContent(/Bitter Gourd/i);

    expect(screen.getByTestId("retake-photos-btn")).toBeInTheDocument();
    expect(screen.getByTestId("change-crop-btn")).toBeInTheDocument();
  });

  it("renders GRADE_UNAVAILABLE error state with lighting tips and retake button", () => {
    renderStep3({
      error: { code: "GRADE_UNAVAILABLE", message: "Confidence below threshold" },
    });

    const errorAlert = screen.getByTestId("ai-error-grade-unavailable");
    expect(errorAlert).toBeInTheDocument();
    expect(errorAlert).toHaveTextContent(/Quality grade unavailable/i);
    expect(errorAlert).toHaveTextContent(/confidence below 55%/i);
    expect(errorAlert).toHaveTextContent(/natural daylight/i);

    expect(screen.getByTestId("retake-photos-btn")).toBeInTheDocument();
  });
});
